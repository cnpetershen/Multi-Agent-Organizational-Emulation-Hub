import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import type { CompanyId, UserId } from '@maoeh/shared-types';
import {
  slugifyId,
  uniqueId,
  type OwnedOrganization,
  type OwnershipState,
  type User,
} from '@maoeh/organization-model';

/**
 * M1.5 · AI company ownership.
 *
 * `User (founder) owns Organization (AI company) employs Agents` — the one relationship this
 * milestone adds. The store is deliberately *not* an account system: a founder is a name, a
 * company is a name plus an owner, and activation is "which company the runtime is running",
 * never "what this person is allowed to do". No password, no token, no permission model
 * (explicitly out of scope for M1.5).
 *
 * Durability follows the event log's rule (composition.ts): state lives *outside the
 * repository*, in the platform's per-user state directory, so a `git clean` cannot fire a
 * founder from their own company. `path: null` is the isolated in-memory store every test
 * and every `MAOEH_EVENT_LOG=off` run uses.
 */

/** The founder a fresh install already has — so "Sign in" is a real destination before anyone creates anything. */
export const DEFAULT_FOUNDER_NAME = 'Guest Founder';
/** The company a fresh install already runs: the M0–M1 seed organization, now owned. */
export const DEFAULT_COMPANY_ID = 'future-ai-lab' as CompanyId;
export const DEFAULT_COMPANY_NAME = 'Future AI Lab';

const FOUNDER_NAME_MAX = 100;
const COMPANY_NAME_MAX = 120;

export interface CreateCompanyInput {
  readonly founderName: string;
  readonly companyName: string;
}

export interface OwnershipSuccess {
  readonly ok: true;
  readonly user: User;
  readonly organization: OwnedOrganization;
}

export interface OwnershipFailure {
  readonly ok: false;
  /** Machine-readable reason; the UI localizes it, the API never sends prose. */
  readonly code:
    | 'founder_name_required'
    | 'founder_name_too_long'
    | 'company_name_required'
    | 'company_name_too_long'
    | 'unknown_organization';
  readonly message: string;
}

export type OwnershipResult = OwnershipSuccess | OwnershipFailure;

export interface OwnershipStore {
  /** The whole ownership record: founders, their companies, and the one the runtime runs. */
  state(): OwnershipState;
  /** Seed `Guest Founder` + `Future AI Lab` when the store is empty — idempotent. */
  ensureDefaults(): void;
  /**
   * `Founder → Company Name → 公司`: creates the founder (reusing an existing name), creates
   * the company owned by them, and signs them in by making it the active organization. The
   * CEO agent is *not* created here — it is generated by composing the company's starter
   * organization, which is what the caller does next.
   */
  createCompany(input: CreateCompanyInput): OwnershipResult;
  /** Sign in to an existing company. */
  activate(organizationId: string): OwnershipResult;
}

interface PersistedOwnership {
  readonly version: 1;
  readonly users: readonly User[];
  readonly organizations: readonly OwnedOrganization[];
  readonly activeOrganizationId: string;
}

function failure(code: OwnershipFailure['code'], message: string): OwnershipFailure {
  return { ok: false, code, message };
}

function cleanName(value: unknown): string {
  return typeof value === 'string' ? value.trim() : '';
}

function isPersisted(value: unknown): value is PersistedOwnership {
  if (typeof value !== 'object' || value === null) return false;
  const record = value as { version?: unknown; users?: unknown; organizations?: unknown; activeOrganizationId?: unknown };
  return (
    record.version === 1 &&
    Array.isArray(record.users) &&
    Array.isArray(record.organizations) &&
    typeof record.activeOrganizationId === 'string'
  );
}

function readPersisted(path: string): PersistedOwnership | null {
  try {
    if (!existsSync(path)) return null;
    const parsed: unknown = JSON.parse(readFileSync(path, 'utf8'));
    return isPersisted(parsed) ? parsed : null;
  } catch {
    // A damaged ownership file must not keep the console from booting: the store falls back to
    // the default company rather than taking the whole API down with it.
    return null;
  }
}

function writePersisted(path: string, state: PersistedOwnership): void {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.tmp`;
  writeFileSync(temporary, JSON.stringify(state, null, 2), 'utf8');
  renameSync(temporary, path);
}

export function createOwnershipStore(options: { readonly path?: string | null } = {}): OwnershipStore {
  const path = options.path ?? null;
  const persisted = path === null ? null : readPersisted(path);
  const users: User[] = persisted === null ? [] : [...persisted.users];
  const organizations: OwnedOrganization[] = persisted === null ? [] : [...persisted.organizations];
  let activeOrganizationId: CompanyId | null =
    persisted === null ? null : (persisted.activeOrganizationId as CompanyId);

  const save = (): void => {
    if (path === null) return;
    writePersisted(path, {
      version: 1,
      users,
      organizations,
      activeOrganizationId: String(activeOrganizationId ?? ''),
    });
  };

  const state = (): OwnershipState => ({
    users: [...users],
    organizations: [...organizations],
    activeOrganizationId: activeOrganizationId ?? DEFAULT_COMPANY_ID,
  });

  const findUserByName = (name: string): User | undefined =>
    users.find((user) => user.name.toLowerCase() === name.toLowerCase());

  const ensureDefaults = (): void => {
    let changed = false;
    if (users.length === 0) {
      users.push({ id: 'user-guest-founder' as UserId, name: DEFAULT_FOUNDER_NAME });
      changed = true;
    }
    if (organizations.length === 0) {
      const ownerId = users[0]?.id;
      if (ownerId !== undefined) {
        organizations.push({
          id: DEFAULT_COMPANY_ID,
          name: DEFAULT_COMPANY_NAME,
          ownerId,
          seed: 'lab',
        });
        changed = true;
      }
    }
    if (activeOrganizationId === null || !organizations.some((org) => org.id === activeOrganizationId)) {
      const first = organizations[0];
      if (first !== undefined) {
        activeOrganizationId = first.id;
        changed = true;
      }
    }
    if (changed) save();
  };

  const adopt = (user: User, organization: OwnedOrganization): OwnershipSuccess => {
    activeOrganizationId = organization.id;
    save();
    return { ok: true, user, organization };
  };

  const createCompany = ({ founderName, companyName }: CreateCompanyInput): OwnershipResult => {
    const name = cleanName(founderName);
    if (name === '') return failure('founder_name_required', 'a founder needs a name');
    if (name.length > FOUNDER_NAME_MAX) {
      return failure('founder_name_too_long', `a founder name is at most ${String(FOUNDER_NAME_MAX)} characters`);
    }
    const company = cleanName(companyName);
    if (company === '') return failure('company_name_required', 'a company needs a name');
    if (company.length > COMPANY_NAME_MAX) {
      return failure('company_name_too_long', `a company name is at most ${String(COMPANY_NAME_MAX)} characters`);
    }

    const existing = findUserByName(name);
    const user: User =
      existing ??
      ({
        id: uniqueId(`user-${slugifyId(name, 'founder')}`, new Set(users.map((entry) => String(entry.id)))) as UserId,
        name,
      });
    if (existing === undefined) users.push(user);

    const organization: OwnedOrganization = {
      id: uniqueId(
        slugifyId(company, 'company'),
        new Set(organizations.map((entry) => String(entry.id))),
      ) as CompanyId,
      name: company,
      ownerId: user.id,
      seed: 'starter',
    };
    organizations.push(organization);
    return adopt(user, organization);
  };

  const activate = (organizationId: string): OwnershipResult => {
    const organization = organizations.find((entry) => entry.id === organizationId);
    if (organization === undefined) return failure('unknown_organization', `unknown company "${organizationId}"`);
    const user = users.find((entry) => entry.id === organization.ownerId);
    if (user === undefined) return failure('unknown_organization', `company "${organizationId}" has no founder`);
    activeOrganizationId = organization.id;
    save();
    return { ok: true, user, organization };
  };

  return { state, ensureDefaults, createCompany, activate };
}
